import { test, expect } from '@playwright/test'

async function open(page: import('@playwright/test').Page, path: string) {
  await page.goto('/')
  await page.getByLabel('Password', { exact: true }).fill('fake-e2e-password-123')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your expo library.' })).toBeVisible()
  await page.goto(path)
}

test('settings panels save preferences and backups, and reject an invalid ChatGPT import', async ({ page }) => {
  await open(page, '/settings')
  await page.getByLabel('Colour theme', { exact: true }).selectOption('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByLabel('Colour theme', { exact: true }).selectOption('light')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByLabel('Phone number region hint').fill('IN')
  await page.getByLabel('Phone number region hint').blur()
  await page.getByRole('button', { name: 'Save connections & models' }).click()
  await expect(page.getByRole('status')).toContainText('Connection and model choices saved')
  await page.getByText('Backups & recovery', { exact: true }).click()
  await page.getByLabel('Daily snapshots to keep').fill('3')
  await page.getByLabel('Weekly snapshots to keep').fill('2')
  await page.getByRole('button', { name: 'Save schedule', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Backup schedule saved')
  await page.getByRole('button', { name: 'Back up now', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Backup queued')
  await page.getByRole('button', { name: 'Connect from another PC', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Import protected connection file').setInputFiles({ name: 'invalid.expo', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.getByRole('alert')).toContainText('Check the form and try again')
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await page.reload()
  await page.getByText('Backups & recovery', { exact: true }).click()
  await expect(page.getByLabel('Daily snapshots to keep')).toHaveValue('3')
  await expect(page.getByLabel('Phone number region hint')).toHaveValue('IN')
})

test('all main panels render, filters open, and source controls preserve the original', async ({ page }) => {
  await open(page, '/library')
  for (const path of ['/health', '/review', '/grouping', '/expos', '/library/people', '/library/companies', '/exports', '/upload', '/capture']) {
    await page.goto(path)
    await expect(page.locator('main h1')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  }
  await page.goto('/library')
  await page.getByRole('button', { name: 'List view' }).click()
  await page.getByRole('button', { name: 'Grid view' }).click()
  await page.getByText('More filters', { exact: true }).click()
  await page.getByLabel('Review', { exact: true }).selectOption('reviewed')
  await page.getByLabel('Review', { exact: true }).selectOption('')
  await page.getByRole('button', { name: 'Trash', exact: true }).click()
  await page.getByRole('button', { name: 'Back to library', exact: true }).click()
  const first = page.locator('.document-link').first()
  await expect(first).toBeVisible()
  await first.click()
  await page.getByRole('button', { name: 'Crop', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveAccessibleName('Choose the area to read')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  const rotation = page.waitForResponse(response => response.url().endsWith('/rotate'))
  await page.getByRole('button', { name: 'Rotate', exact: true }).click()
  expect((await rotation).status()).toBe(200)
  await page.getByText('Source history', { exact: true }).click()
  await expect(page.getByText('Reading copy changed').first()).toBeVisible()
  await page.getByRole('button', { name: 'Ask AI again', exact: true }).click()
  await page.getByRole('button', { name: 'Read the company logo', exact: true }).click()
  await expect(page.getByLabel('Note or instructions for AI')).toHaveValue(/Read the company logo/)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Mark reviewed', exact: true }).click()
  await page.getByRole('button', { name: 'Use as a checked accuracy example' }).click()
  await page.getByRole('button', { name: 'I checked these fields against the photo' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Trash', exact: true }).click()
  await page.getByRole('button', { name: 'Keep document', exact: true }).click()
  await page.getByRole('button', { name: 'Trash', exact: true }).click()
  await page.getByRole('button', { name: 'Move to Trash', exact: true }).click()
  await page.getByRole('button', { name: 'Trash', exact: true }).click()
  await page.getByRole('button', { name: 'Remove originals permanently', exact: true }).first().click()
  await expect(page.getByRole('dialog')).toHaveAccessibleName('Remove original files permanently?')
  await page.getByRole('button', { name: 'Keep files', exact: true }).click()
  await page.getByRole('button', { name: 'Restore', exact: true }).first().click()
  await expect(page.getByRole('status')).toContainText('Document restored')
})
