import { test, expect } from '@playwright/test'

test.skip(!process.env.AUDIT_REVIEW_FIXTURES, 'Requires synthetic review fixtures in the isolated audit database')

test('review individual contact changes beside source, guard exports, show status and dismiss phone reports', async ({ page }, info) => {
  await page.goto('/')
  await page.getByLabel('Password', {exact:true}).fill('fake-e2e-password-123')
  await page.getByRole('button', {name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading', {name:'Your expo library.'})).toBeVisible()
  const fixture = await page.evaluate(async mode => {
    const expos = await (await fetch('/api/v1/expos')).json()
    return expos.filter((row:any)=>row.name.startsWith('SYNTHETIC Review '+mode+' ')).sort((a:any,b:any)=>b.created_at.localeCompare(a.created_at))[0] as {id:string;name:string}
  }, info.project.name)
  const name = fixture.name
  await page.getByLabel('Active expo').selectOption(fixture.id)
  await page.waitForFunction(id=>new Promise<boolean>(resolve=>{const request=indexedDB.open('expo-capture',1);request.onsuccess=()=>{const db=request.result;const get=db.transaction('meta').objectStore('meta').get('activeExpo');get.onsuccess=()=>{resolve(get.result?.value===id);db.close()}}}),fixture.id)
  await expect(page.getByRole('link', {name:/Review details/})).toContainText('1 documents · 1 suggestions')
  await page.goto('/review')
  await expect(page.locator('.proposal-card')).toHaveCount(1)
  const card = page.locator('.proposal-card')
  await expect(card.getByRole('heading',{name})).toBeVisible()
  await expect(card.getByRole('button',{name:'Enlarge source image'})).toBeVisible()
  await expect(card.getByRole('img',{name:'Source document'})).toBeVisible()
  await expect(card).not.toContainText('page_id')
  const invalid = card.getByRole('checkbox',{name:'add email: broken@@example.com',exact:true})
  await expect(invalid).toBeDisabled()
  await expect(card.getByText(/already saved as/)).toBeVisible()
  await expect(card.getByRole('checkbox')).toHaveCount(3)
  const source = await card.getByRole('link',{name:'Open source & edit'}).getAttribute('href')
  await page.screenshot({path:info.outputPath('review-comparison.png'), fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
  await page.goto(source!)
  await expect(page.locator('.document-status').first()).toContainText('Processing complete')
  await expect(page.locator('.document-status').first()).toContainText('Review: Needs attention')
  await expect(page.getByText('Grouping confirmed',{exact:true})).toBeVisible()
  // Exporting flagged contact fields requires an explicit choice and carries warnings.
  await page.goto('/exports')
  await page.getByRole('button',{name:'2 Tables',exact:true}).click()
  await page.getByLabel('Contacts', {exact:false}).uncheck()
  await page.getByLabel('Companies', {exact:false}).check()
  await page.getByRole('button',{name:'4 Preview',exact:true}).click()
  await expect(page.getByRole('columnheader',{name:'Review warning',exact:true})).toBeVisible()
  await expect(page.getByText(/Unresolved suggested changes/).first()).toBeVisible()
  await page.getByRole('button',{name:'5 Format',exact:true}).click()
  await expect(page.getByRole('button',{name:'Generate export',exact:true})).toBeDisabled()
  await page.getByLabel('Include unreviewed or flagged data in this export').check()
  await expect(page.getByRole('button',{name:'Generate export',exact:true})).toBeEnabled()
  const started=page.waitForResponse(r=>r.url().endsWith('/api/v1/exports') && r.request().method()==='POST')
  await page.getByRole('button',{name:'Generate export',exact:true}).click()
  const exportId=(await (await started).json()).id
  const downloadRow=page.locator('.recent-row').filter({has:page.locator(`a[href="/api/v1/exports/${exportId}/download"]`)})
  await expect(downloadRow.getByRole('link',{name:'Download',exact:true})).toBeVisible({timeout:45000})
  const downloadEvent=page.waitForEvent('download')
  await downloadRow.getByRole('link',{name:'Download',exact:true}).click()
  const download=await downloadEvent
  await download.saveAs(info.outputPath('review-warning.xlsx'))
  expect(download.suggestedFilename()).toMatch(/\.xlsx$/)
  await page.goto('/review')
  await page.locator('.proposal-card').getByRole('checkbox',{name:'add email: new@example.com',exact:true}).check()
  await page.locator('.proposal-card').getByRole('button',{name:'Apply checked changes',exact:true}).click()
  await expect(page.locator('.proposal-card')).toHaveCount(0)
  await page.getByRole('button',{name:'Mark reviewed',exact:true}).click()
  await expect(page.getByText('Everything looks good',{exact:true})).toBeVisible()
  await page.goto(source!)
  await expect(page.locator('.document-status').first()).toContainText('Review: Reviewed')
  await expect(page.getByText('new@example.com',{exact:true}).first()).toBeVisible()
  await expect(page.getByText('broken@@example.com',{exact:true})).toHaveCount(0)
  // Device reports update in place; zero queues stay hidden; dismissal never touches capture data.
  const device='10000000-0000-4000-8000-'+(info.project.name==='desktop'?'000000000001':'000000000002')
  await page.evaluate(async client_uuid=>{
    const csrf=document.cookie.split('; ').find(x=>x.startsWith('expo_csrf='))!.split('=')[1]
    for(const files of [1,2]) await fetch('/api/v1/sync/report',{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':csrf},body:JSON.stringify({client_uuid,device_label:'SYNTHETIC Test Phone',files,notes:0,bytes:20})})
  },device)
  await page.goto('/')
  const report=page.locator('.system-row').filter({hasText:'SYNTHETIC Test Phone'})
  await expect(report).toHaveCount(1)
  await expect(report).toContainText('2 files')
  await report.getByRole('button',{name:'Dismiss report'}).click()
  await expect(report).toHaveCount(0)
})

test('slow search shows a loading state until the response arrives', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Password', {exact:true}).fill('fake-e2e-password-123')
  await page.getByRole('button', {name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading', {name:'Your expo library.'})).toBeVisible()
  let release!: () => void
  const gate=new Promise<void>(resolve=>{release=resolve})
  await page.route('**/api/v1/search?*', async route=>{ await gate; await route.fulfill({json:{results:[],total:0}}) })
  await page.goto('/library?q=synthetic-slow-search')
  await expect(page.getByText('No matching records',{exact:true})).toHaveCount(0)
  await expect(page.getByRole('status').filter({hasText:/Loading/})).toBeVisible()
  release()
  await expect(page.getByText('No matching records',{exact:true})).toBeVisible()
})
